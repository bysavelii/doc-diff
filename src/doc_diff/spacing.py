def collapse_whitespace(text: str) -> str:
    """Любая серия пробельных символов (пробелы, табуляции, переводы строк, неразрывные
    пробелы) становится одним пробелом, края обрезаются.

    Одно правило для PDF и DOCX: иначе один и тот же договор в двух форматах
    расходился бы на пустом месте.
    """
    return " ".join(text.split())
